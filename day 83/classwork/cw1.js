let mymap = new Map(
    [['a', 1],
    ['b', 2], 
    ['c', 3]
]
)

mymap.delete('b') //წაშლის b-ს მაპიდან. პითონიდან მახსენებს pop მეთოდს
mymap.set('d', 4)//დაამატებს d-ს 4-ის მნიშვნელობით. პითონიდან მახსენებს update მეთოდს
mymap.has('a')//შეამოწმებს თუ a-ს აქვს მნიშვნელობა. პითონიდან მახსენებს in ოპერატორს
mymap.get('c')//მიიღბს c-ს მნიშვნელობას. პითონიდან მახსენებს get მეთოდს
mymap.clear() //წაშლის ყველა ელემენტს მაპიდან. პითონიდან მახსენებს clear მეთოდს



console.log(mymap.keys())
console.log(mymap.values())
console.log(mymap.entries())

console.log(mymap)


