myset.has(4) //ამოწმებს თუ 4 არის სეტში. პითონიდან მახსენებს in ოპერატორს 
myset.clear() //წაშლის ყველა ელემენტს სეტიდან. პითონიდან მახსენებს clear მეთოდს
